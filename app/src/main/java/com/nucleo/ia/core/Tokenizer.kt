    fun encode(text: String): IntArray {
        val out = IntArray(SEQ_LEN)
        val lower = text.lowercase().trim()
        var i = 0
        var pos = 0

        while (pos < lower.length && i < SEQ_LEN) {
            var matched = false
            for (len in minOf(lower.length - pos, 25) downTo 1) {
                val candidate = lower.substring(pos, pos + len)
                wordMap[candidate]?.let { id ->
                    if (i < SEQ_LEN) {
                        out[i] = id
                        i++
                    }
                    pos += len
                    matched = true
                    return@let
                }
            }
            if (!matched) {
                val ch = lower[pos]
                val id = charMap[ch] ?: 0
                if (i < SEQ_LEN) {
                    out[i] = id
                    i++
                }
                pos++
            }
        }
        return out
    }

    fun decode(ids: IntArray): String {
        val reverseChar = charMap.entries.associate { (k, v) -> v to k }
        val reverseWord = wordMap.entries.associate { (k, v) -> v to k }
        return ids.filter { it != 0 }.mapNotNull { id ->
            reverseWord[id] ?: reverseChar[id]
        }.joinToString("")
    }
